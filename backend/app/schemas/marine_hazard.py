"""Typed schemas for marine wave and weather hazard conditions.

Data model based on the verified Open-Meteo Marine Weather API response
structure, confirmed via live probe on 2026-10-26 at latitude 13.375N,
longitude 74.708E (Karnataka coast, near Malpe).

Source: https://marine-api.open-meteo.com/v1/marine
Access: No API key required for non-commercial use.
Update cadence: Hourly. Model: ERAssWave (European Reanalysis + ECMWF-based)
"""

from __future__ import annotations

from datetime import datetime
from enum import Enum
from typing import List, Optional

from pydantic import BaseModel, Field


class WaveHazardLevel(str, Enum):
    """Exploratory prototype hazard classification derived from combined significant wave height.

    DOCUMENTED SOURCE:
    - Douglas Sea State Scale & World Meteorological Organization (WMO) Code Table 3700.
    - Adapted in SaagarDrishti solely as a prototype descriptive heuristic for
      small coastal craft (<15 m Length Overall).

    CRITICAL REGULATORY NOTICE:
    - These thresholds are NOT statutory warnings issued by the India Meteorological
      Department (IMD) or Karnataka Department of Fisheries (DFO).
    - These thresholds are NOT universal vessel-safety limits.
    - Low wave height does NOT confirm that maritime conditions are safe.
    - Small-craft fishers must strictly defer to official IMD/DFO warnings.
    """

    CALM = "calm"                   # wave_height < 0.5 m (Douglas state 0-2)
    SLIGHT = "slight"               # 0.5 - 1.25 m (Douglas state 3)
    MODERATE = "moderate"           # 1.25 - 2.5 m (Douglas state 4)
    ROUGH = "rough"                 # 2.5 - 4.0 m (Douglas state 5)
    VERY_ROUGH = "very_rough"       # > 4.0 m (Douglas state 6+)
    UNKNOWN = "unknown"             # data missing, null, or model unavailable


class HourlyMarineForecastStep(BaseModel):
    """Single-hour numerical weather prediction (NWP) model forecast step.

    NOTE: This is a numerical model forecast generated by ECMWF/ERAssWave,
    NOT an in-situ buoy or coastal sensor observation.
    """

    time_local: str = Field(..., description="ISO 8601 local time in the configured timezone")
    is_model_forecast: bool = Field(
        True, description="Always True: distinguishes NWP model forecast values from in-situ sensor observations"
    )
    wave_height_m: Optional[float] = Field(None, description="Combined significant wave height forecast (m)")
    wind_wave_height_m: Optional[float] = Field(None, description="Wind-generated wave height component forecast (m)")
    swell_wave_height_m: Optional[float] = Field(None, description="Swell wave height component forecast (m)")
    wave_direction_deg: Optional[float] = Field(None, description="Mean wave propagation direction, degrees from N (0-360)")
    wave_period_s: Optional[float] = Field(None, description="Mean wave period forecast (s)")
    wind_wave_direction_deg: Optional[float] = Field(None, description="Wind-wave propagation direction, deg from N")
    swell_wave_direction_deg: Optional[float] = Field(None, description="Swell propagation direction, deg from N")
    swell_wave_period_s: Optional[float] = Field(None, description="Swell wave period forecast (s)")
    hazard_level: WaveHazardLevel = Field(
        WaveHazardLevel.UNKNOWN, description="Derived prototype small-craft hazard level (Douglas/WMO scale)"
    )


# Backwards compatibility alias
HourlyMarineObservation = HourlyMarineForecastStep


class MarineHazardForecast(BaseModel):
    """Structured marine wave model forecast for a single geographic point.

    Represents a normalised slice of the Open-Meteo Marine API NWP model output.
    Provenance, grid resolution, and temporal metadata are mandatory; the absence
    of high waves or official warnings is explicitly distinguished from confirmed
    safe conditions.
    """

    source: str = Field(..., description="Data source identifier")
    source_url: str = Field(..., description="Exact request URL used to retrieve this payload")
    retrieved_at: datetime = Field(..., description="UTC timestamp when the payload was fetched")
    model_label: str = Field("ERAssWave", description="Underlying NWP wave model label")
    latitude: float = Field(..., description="Snapped latitude returned by the model grid")
    longitude: float = Field(..., description="Snapped longitude returned by the model grid")
    grid_resolution_km: float = Field(
        9.0, description="Approximate spatial resolution of the model grid (~0.083° to 0.1°)"
    )
    timezone: str = Field(..., description="Timezone label used for local times")
    utc_offset_seconds: int = Field(..., description="UTC offset in seconds for local times")
    forecast_hours: List[HourlyMarineForecastStep] = Field(
        default_factory=list, description="Hourly NWP model forecast time steps"
    )
    current_hour_observation: Optional[HourlyMarineForecastStep] = Field(
        None, description="Model forecast step for the current/closest hour, or None if unavailable"
    )
    forecast_valid_time: Optional[str] = Field(
        None, description="Local timestamp corresponding to the active forecast step"
    )
    is_stale: bool = Field(
        False, description="Flagged True if all forecast steps are in the past relative to local time"
    )
    is_data_available: bool = Field(
        True, description="Flagged False if model data is empty or missing wave heights"
    )
    peak_wave_height_m: Optional[float] = Field(
        None, description="Maximum wave_height_m across all forecast hours"
    )
    peak_hazard_level: WaveHazardLevel = Field(
        WaveHazardLevel.UNKNOWN, description="Worst prototype hazard level across all forecast hours"
    )
    data_quality_notes: List[str] = Field(
        default_factory=list, description="Known limitations and quality flags"
    )
    # Safety critical: absence of warning != safe
    safety_disclaimer: str = Field(
        default=(
            "Open-Meteo marine forecasts are numerical model outputs (NWP), NOT authoritative safety advisories. "
            "Low or absent wave heights DO NOT confirm that sea conditions are safe for navigation. "
            "Threshold classifications are prototype descriptive heuristics based on the Douglas sea scale, "
            "NOT official IMD warnings. Always consult official India Meteorological Department (IMD) "
            "Marine Weather Bulletins and Karnataka DFO notices before departure."
        ),
        description="Mandatory safety disclaimer attached to every forecast payload.",
    )

